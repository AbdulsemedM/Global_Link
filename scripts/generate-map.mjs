// Generates the trade-network map: public/images/map/land.svg (land mask) and
// src/components/visuals/map-data.ts (projected graticule, Ethiopia outline, routes and ports).
//
//   npm run generate:map
//
// To add a lane: add its waypoints to `routes` below (lon, lat), add the place to `places`,
// add a matching entry to `lanes` in src/lib/site.ts and a label in trade-network.tsx.
import fs from 'node:fs'
import { createRequire } from 'node:module'
import { feature } from 'topojson-client'
import { presimplify, simplify, quantile } from 'topojson-simplify'
import { geoNaturalEarth1, geoPath, geoGraticule } from 'd3-geo'
import { line, curveCatmullRom } from 'd3-shape'

const require = createRequire(import.meta.url)
const OUT_SVG = 'public/images/map/land.svg'
const OUT_TS = 'src/components/visuals/map-data.ts'

// Natural Earth 1:50m, simplified (Visvalingam) to keep the 25% most significant points
const simplified = (name) => {
  const t = presimplify(JSON.parse(fs.readFileSync(require.resolve(`world-atlas/${name}`))))
  return simplify(t, quantile(t, 0.25))
}
const landTopo = simplified('land-50m.json')
const land = feature(landTopo, landTopo.objects.land)
const countries = simplified('countries-50m.json')
const ethiopia = feature(countries, countries.objects.countries).features.find((f) => f.id === '231')

// Region: East Africa → East Asia (no European lanes), framed to give the Horn of Africa room
const W = 1200
const bbox = { type: 'MultiPoint', coordinates: [] }
for (let lon = 26; lon <= 125; lon += 2) bbox.coordinates.push([lon, -6], [lon, 40])
const projection = geoNaturalEarth1().rotate([-75, 0]).fitWidth(W, bbox)
const [[, y0], [, y1]] = geoPath(projection).bounds(bbox)
const H = Math.round(y1 - y0)
projection.translate([projection.translate()[0], projection.translate()[1] - y0]).clipExtent([[0, 0], [W, H]])
const path = geoPath(projection).digits(0)

const P = ([lon, lat]) => projection([lon, lat]).map((v) => Math.round(v * 10) / 10)
const smooth = line().curve(curveCatmullRom.alpha(0.5))
const route = (pts) => smooth(pts.map(P)).replace(/(\.\d)\d+/g, '$1')

// Overland lanes follow the main highways and border crossings; sea lanes use waypoints so they never cross land
const ADD = [38.75, 9.03]
const DJI = [43.15, 11.59]
const east = [DJI, [44.8, 11.9], [48.5, 12.8]] // Gulf of Aden
const routes = {
  // Road: Addis Ababa → Adama → Awash → Dire Dawa (customs) → Djibouti
  djibouti: route([ADD, [39.27, 8.54], [40.17, 8.98], [41.86, 9.59], [42.6, 10.6], DJI]),
  // Road: Addis Ababa → Dire Dawa → Jijiga (customs) → Hargeisa
  somalia: route([ADD, [40.17, 8.98], [41.86, 9.59], [42.8, 9.35], [44.06, 9.56]]),
  // Road: Addis Ababa → Hawassa → Moyale (border) → Isiolo → Nairobi
  kenya: route([ADD, [38.48, 7.06], [38.4, 5.2], [39.06, 3.53], [37.58, 0.35], [36.82, -1.29]]),
  // Sea from Djibouti
  karachi: route([...east, [53, 13.8], [60, 17.5], [64.5, 22.5], [66.98, 24.85]]),
  jebelAli: route([...east, [52.5, 14.2], [57, 17.2], [59.5, 21.5], [59.4, 23.6], [57.6, 25.3], [56.4, 26.45], [55.4, 25.9], [55.03, 25.01]]),
  shanghai: route([...east, [53, 12.2], [62, 9.5], [72, 7], [80.5, 5.6], [88, 5.8], [95, 6], [98.5, 4.5], [101.5, 2.6], [103.9, 1.2], [105.5, 3.5], [109, 9], [112.5, 15.5], [117, 21.5], [120.5, 26.5], [122.4, 30.2], [121.47, 31.23]]),
}
const places = {
  addis: P(ADD),
  direDawa: P([41.86, 9.59]),
  jijiga: P([42.8, 9.35]),
  djibouti: P(DJI),
  hargeisa: P([44.06, 9.56]),
  moyale: P([39.06, 3.53]),
  nairobi: P([36.82, -1.29]),
  karachi: P([66.98, 24.85]),
  jebelAli: P([55.03, 25.01]),
  shanghai: P([121.47, 31.23]),
}

fs.mkdirSync('public/images/map', { recursive: true })
fs.writeFileSync(OUT_SVG, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><path d="${path(land)}"/></svg>`)
fs.writeFileSync(
  OUT_TS,
  `// Generated by scripts/generate-map.mjs from Natural Earth (world-atlas, 1:50m) — do not edit by hand.
// Coordinates are projected screen positions in a ${W}×${H} viewBox (Natural Earth projection, rotated to 75°E).
export const MAP_WIDTH = ${W}
export const MAP_HEIGHT = ${H}

export const graticulePath = '${geoPath(projection).digits(0)(geoGraticule().step([10, 10])())}'

export const ethiopiaPath = '${path(ethiopia)}'

export const routePaths = ${JSON.stringify(routes, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")} as const

export const places = ${JSON.stringify(places).replace(/"(\w+)":/g, '$1: ').replace(/,(?=\w)/g, ', ')} as const
`
)
console.log(`Map written: ${OUT_SVG} (${Math.round(fs.statSync(OUT_SVG).size / 1024)} KB), ${OUT_TS}`)
